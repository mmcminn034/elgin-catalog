"""Generate supabase/seed/011_reference_fossil_mineral_seed.sql from public-fossils.json + public-minerals.json (idempotent upsert; needs migration 011)."""
import json
cols = ["id","name","aliases","typology_system","category","period","dates","continent","country","admin1","region_notes","traits","similar_types","texas","home_priority","sources",
        "rules","group_id","fossil_kind","age_ma","formations","lookalikes","localities","taxonomy","properties","diagnostic"]
rows = []
for f in ["data/reference/public-fossils.json", "data/reference/public-minerals.json"]:
    for t in json.load(open(f))["types"]:
        r = {k: t.get({"group_id": "group"}.get(k, k)) for k in cols}
        for k in ("aliases","country","admin1","traits","similar_types","formations","lookalikes","localities"): r[k] = r[k] or []
        r["age_ma"] = [x for x in (r["age_ma"] or []) if x is not None] or None
        r["home_priority"] = r["home_priority"] or 3; r["texas"] = bool(r["texas"]); r["rules"] = bool(r["rules"]); rows.append(r)
payload = json.dumps(rows, ensure_ascii=False).replace("$ref$", "")
upd = ", ".join(f"{c} = excluded.{c}" for c in cols if c != "id")
sql = f"""-- generated by tools/reference/gen_seed_sql_fm.py ({len(rows)} rows). Run after 011_reference_fossil_mineral.sql. NOT APPLIED.
insert into public.reference_types ({", ".join(cols)})
select {", ".join("x." + c for c in cols)}
from jsonb_populate_recordset(null::public.reference_types, $ref${payload}$ref$::jsonb) x
on conflict (id) do update set {upd}, updated_at = now();
"""
open("supabase/seed/011_reference_fossil_mineral_seed.sql", "w").write(sql); print(len(rows))
